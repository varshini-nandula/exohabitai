def test_list_users(client, seed_users):
    """Get /admin/users lists all users with filtering support."""
    headers = create_admin(client)
    resp = client.get("/admin/users", headers=headers)
    assert resp.status_code == 200

    data = resp.get_json()["data"]
    users = data["users"]
    # Total users including the admin generated by create_admin
    assert len(users) >= 4

    # Search filter
    resp = client.get("/admin/users?search=moderator", headers=headers)
    assert resp.status_code == 200
    users = resp.get_json()["data"]["users"]
    assert len(users) == 1
    assert users[0]["username"] == "moderator"

    # Role filter
    resp = client.get("/admin/users?role=admin", headers=headers)
    assert resp.status_code == 200
    users = resp.get_json()["data"]["users"]
    assert all(u["role"] == "admin" for u in users)


