def test_activate_deactivate_user(client, seed_users):
    """Admins can deactivate and reactivate users, and deactivation blocks login."""
    u1_id, u2_id, _ = seed_users
    headers = create_admin(client)

    # Deactivate 'moderator'
    resp = client.post(f"/admin/users/{u1_id}/deactivate", headers=headers)
    assert resp.status_code == 200
    with client.application.app_context():
        u = db.session.get(User, u1_id)
        assert u.is_active is False

    # Try logging in as deactivated user
    resp = login_user(client, username="moderator", password="pass1234")
    assert resp.status_code == 401
    assert "deactivated" in resp.get_json()["message"].lower() or "inactive" in resp.get_json()["message"].lower()

    # Reactivate
    resp = client.post(f"/admin/users/{u1_id}/activate", headers=headers)
    assert resp.status_code == 200
    with client.application.app_context():
        u = db.session.get(User, u1_id)
        assert u.is_active is True

    # Try logging in again
    resp = login_user(client, username="moderator", password="pass1234")
    assert resp.status_code == 200


def test_promote_demote_user(client, seed_users):
    """Admins can promote users to admin and demote admins."""
    u1_id, _, _ = seed_users
    headers = create_admin(client)

    # Promote
    resp = client.post(f"/admin/users/{u1_id}/promote", headers=headers)
    assert resp.status_code == 200
